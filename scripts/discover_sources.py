"""Discover source pages on rijksoverheid.nl for a fixed list of topics.

Run once by hand: `uv run python scripts/discover_sources.py`.
The output (data/sources.txt) is committed and reviewed, so ingestion stays reproducible
even if the site's navigation changes later.
"""

import re
import time
from pathlib import Path

import httpx

BASE = "https://www.rijksoverheid.nl"
TOPICS = [
    "/themas/onderwijs/studiefinanciering",
    "/themas/belastingen-uitkeringen-en-toeslagen/kinderopvangtoeslag",
    "/themas/familie-zorg-en-gezondheid/zorgverzekering",  # includes "Kan ik zorgtoeslag krijgen?"
    "/themas/bouwen-en-wonen/huurwoning-zoeken",
    "/themas/bouwen-en-wonen/woning-huren",  # includes "Kan ik huurtoeslag krijgen?"
]
# Index pages only list links; sign-language pages are video-only.
SKIP = re.compile(r"gebarentaal|/vraag-en-antwoord$")
USER_AGENT = "rag-nl-overheid/0.1 (student portfolio project; polite crawler)"
DELAY_SECONDS = 1.0


def links_under(html: str, prefix: str) -> set[str]:
    return set(re.findall(rf'href="({re.escape(prefix)}/[^"#?]+)"', html))


def main(out: Path = Path("data/sources.txt")) -> None:
    seen_slugs: set[str] = set()
    urls: list[str] = []
    headers = {"User-Agent": USER_AGENT}
    with httpx.Client(headers=headers, follow_redirects=True, timeout=30) as client:
        for topic in TOPICS:
            found = {topic}
            for page in (topic, topic + "/vraag-en-antwoord"):
                found |= links_under(client.get(BASE + page).text, topic)
                time.sleep(DELAY_SECONDS)
            for path in sorted(found):
                slug = path.rstrip("/").rsplit("/", 1)[-1]
                # The same Q&A page is often linked under two topics; keep one URL per page,
                # otherwise the eval would see two "correct" documents with identical text.
                if SKIP.search(path) or slug in seen_slugs:
                    continue
                seen_slugs.add(slug)
                urls.append(BASE + path)
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/discover_sources.py. One URL per line; '#' starts a comment.\n"
    out.write_text(header + "\n".join(urls) + "\n", encoding="utf-8")
    print(f"Wrote {len(urls)} URLs to {out}")


if __name__ == "__main__":
    main()
